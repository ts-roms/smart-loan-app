const periodsPerYearFor = (f: Scenario["frequency"]) =>
  f === "MONTHLY" ? 12 : f === "BIWEEKLY" ? 26 : 52;

const build = (s: Scenario) =>
  computeAmortizationFor(s.principal, s.annual, s.termMonths, {
    method: s.method,
    frequency: s.frequency,
  });

// ─────────────────────────────────────────────────────────────────────
// 1. VERIFIED — closed-form, independent of this implementation
// ─────────────────────────────────────────────────────────────────────

describe("golden: values derivable without the implementation", () => {
  it.each(SCENARIOS)(
    "$label — first period charges interest on the full principal",
    (s) => {
      // The one interest figure that needs no amortization at all: at
      // installment 1 nothing has been repaid, so interest is simply
      // principal × the period rate.
      const periodRate = s.annual / periodsPerYearFor(s.frequency);
      const rows = build(s);
      if (s.method === "DECLINING") {
        expect(rows[0]!.interest).toBe(r2(s.principal * periodRate));
      }
    },
  );

  it.each(SCENARIOS.filter((s) => s.method === "FLAT"))(
    "$label — flat interest is principal × rate × years",
    (s) => {
      // Add-on interest, the PH standard for motorcycle and small salary
      // lending: computed once on the original principal and split
      // evenly, never recomputed on the declining balance.
      const years = s.termMonths / 12;
      const expected = r2(s.principal * s.annual * years);
      const actual = r2(build(s).reduce((a, x) => a + x.interest, 0));
      expect(actual).toBe(expected);
    },
  );

  it.each(SCENARIOS.filter((s) => s.method === "DECLINING" && s.annual > 0))(
    "$label — instalment matches the annuity formula",
    (s) => {
      // P·r·(1+r)^n / ((1+r)^n − 1), computed here rather than read from
      // the implementation, so the two must independently agree.
      const n = installmentCount(s.termMonths, s.frequency);
      const r = s.annual / periodsPerYearFor(s.frequency);
      const expected = r2(
        (s.principal * r * Math.pow(1 + r, n)) / (Math.pow(1 + r, n) - 1),
      );
      const first = build(s)[0]!;
      // The first instalment is the un-trued-up one, so it equals the
      // formula exactly; the last absorbs the rounding drift.
      expect(Math.abs(first.payment - expected)).toBeLessThanOrEqual(0.01);
      expect(r2(monthlyPayment(s.principal, r, n))).toBe(expected);
    },
  );

  it.each(SCENARIOS)(
    "$label — principal repays exactly, no more, no less",
    (s) => {
      /*
       * The invariant with real money behind it. The loan is booked to
       * Loans Receivable at full principal on disbursement, so if the
       * ROUNDED rows do not sum to the principal, a borrower who pays
       * every instalment in full still leaves a residual on the
       * receivable — a debt that can never be settled.
       */
      const total = r2(build(s).reduce((a, x) => a + x.principal, 0));
      expect(total).toBe(s.principal);
    },
  );

  it.each(SCENARIOS)("$label — every row's payment is its parts", (s) => {
    for (const row of build(s)) {
      expect(row.payment).toBe(r2(row.principal + row.interest));
      expect(row.principal).toBeGreaterThanOrEqual(0);
      expect(row.interest).toBeGreaterThanOrEqual(0);
    }
  });

  it.each(SCENARIOS)("$label — instalment count follows the frequency", (s) => {
    // Weekly is term × 52/12, bi-weekly × 26/12, rounded. A borrower on
    // a 6-month weekly loan pays 26 times, not 24.
    expect(build(s)).toHaveLength(installmentCount(s.termMonths, s.frequency));
  });

  it("declining interest falls every period; flat does not", () => {
    const declining = build(SCENARIOS[0]!);
    for (let i = 1; i < declining.length; i++) {
      expect(declining[i]!.interest).toBeLessThanOrEqual(
        declining[i - 1]!.interest,
      );
    }
    const flat = build(SCENARIOS[1]!);
    for (const row of flat) {
      expect(row.interest).toBe(flat[0]!.interest);
    }
  });
});

