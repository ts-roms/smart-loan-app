  it.each(SCENARIOS)("$label", (s) => {
    const expected = GOLDEN[s.id]!;
    const rows = build(s);
    const first = rows[0]!;
    const lastRow = rows[rows.length - 1]!;

    expect({
      installments: rows.length,
      totalPrincipal: r2(rows.reduce((a, x) => a + x.principal, 0)),
      totalInterest: r2(rows.reduce((a, x) => a + x.interest, 0)),
      totalPayment: r2(rows.reduce((a, x) => a + x.payment, 0)),
      first: {
        principal: first.principal,
        interest: first.interest,
        payment: first.payment,
      },
      last: {
        principal: lastRow.principal,
        interest: lastRow.interest,
        payment: lastRow.payment,
      },
    }).toEqual(expected);
  });

  it("every scenario is covered — no silent gaps in the corpus", () => {
    // A corpus that quietly stops covering a product is worse than no
    // corpus: it still reads as protection.
    expect(Object.keys(GOLDEN).sort()).toEqual(
      SCENARIOS.map((s) => s.id).sort(),
    );
  });
